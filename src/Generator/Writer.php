declare(strict_types=1);

namespace Atrium\WordPress\Generator;

use Atrium\WordPress\Plan\Field;
use Atrium\WordPress\Plan\Plan;
use Atrium\WordPress\Plan\Taxonomy;
use Atrium\WordPress\Plan\Type;
use Illuminate\Support\Str;
use RuntimeException;

/**
 * Writes the modules a WordPress site needs and Atrium does not have: a
 * migration and a model with its admin form for every other post type, every
 * taxonomy and the authors, and the tables linking records to their terms
 * and authors. Like the Bitrix migrator's models, they are meant to be
 * regenerated, not edited.
 */
final class Writer
{
    /** The mark of a file this writer made: only such files are overwritten. */
    public const MARK = 'Generated by atrium:wordpress:generate';

    /** @var array<int,string> */
    private array $written = [];

    /** @var array<int,string> */
    private array $skipped = [];

    public function __construct(
        private readonly string $modelPath,
        private readonly string $migrationPath,
        private readonly bool $force = false,
    ) {}

    /**
     * @return array{written:array<int,string>,skipped:array<int,string>}
     */
    public function write(Plan $plan): array
    {
        $this->written = $this->skipped = [];
        $sequence = 0;

        foreach ($plan->generated() as $type) {
            $this->migration($type->table, $this->typeTable($type), ++$sequence);
            $this->model($type->model, $this->typeModel($plan, $type));
        }

        foreach ($plan->taxonomies as $taxonomy) {
            $this->migration($taxonomy->table, $this->taxonomyTable($taxonomy), ++$sequence);
            $this->model($taxonomy->model, $this->taxonomyModel($plan, $taxonomy));
        }

        $this->migration($plan->authorsTable, $this->authorsTable($plan), ++$sequence);
        $this->model($plan->authorsModel, $this->authorsModel($plan));

        foreach ($plan->moving() as $type) {
            foreach ($type->taxonomies as $name) {
                if (($taxonomy = $plan->taxonomy($name)) !== null) {
                    $this->migration($taxonomy->pivot($type), $this->pivotTable($taxonomy->pivot($type)), ++$sequence);
                }
            }

            $this->migration($plan->authorPivot($type), $this->pivotTable($plan->authorPivot($type)), ++$sequence);
        }

        return ['written' => $this->written, 'skipped' => $this->skipped];
    }

    /**
     * The file of a model class under the model path.
     */
    public function modelFile(string $class): string
    {
        return rtrim($this->modelPath, '/').'/'.class_basename($class).'.php';
    }

    private function migration(string $table, string $body, int $sequence): void
    {
        $existing = glob(rtrim($this->migrationPath, '/').'/*_create_'.$table.'_table.php') ?: [];
        $file = $existing[0] ?? rtrim($this->migrationPath, '/').'/'.date('Y_m_d').'_'.sprintf('%06d', 900000 + $sequence).'_create_'.$table.'_table.php';

        $this->put($file, <<<PHP
            <?php

            // {$this->mark()}

            declare(strict_types=1);

            use Illuminate\\Database\\Migrations\\Migration;
            use Illuminate\\Database\\Schema\\Blueprint;
            use Illuminate\\Support\\Facades\\Schema;

            return new class extends Migration
            {
                public function up(): void
                {
                    Schema::create('{$table}', function (Blueprint \$table): void {
            {$body}
                    });
                }

                public function down(): void
                {
                    Schema::dropIfExists('{$table}');
                }
            };

            PHP);
    }

    private function model(string $class, string $body): void
    {
        $namespace = Str::beforeLast($class, '\\');
        $name = class_basename($class);

        $this->put($this->modelFile($class), <<<PHP
            <?php

            // {$this->mark()}

            declare(strict_types=1);

            namespace {$namespace};

            use Atrium\\Admin\\Columns\\BooleanColumn;
            use Atrium\\Admin\\Columns\\DateColumn;
            use Atrium\\Admin\\Columns\\TextColumn;
            use Atrium\\Admin\\Contracts\\Administrable;
            use Atrium\\Admin\\Fields;
            use Atrium\\Admin\\Traits\\InteractsWithAdmin;
            use Illuminate\\Database\\Eloquent\\Model;
            use Illuminate\\Database\\Eloquent\\Relations\\BelongsToMany;

            class {$name} extends Model implements Administrable
            {
            {$body}
            }

            PHP);
    }

    private function put(string $file, string $content): void
    {
        if (is_file($file) && ! $this->force && ! str_contains((string) file_get_contents($file), self::MARK)) {
            throw new RuntimeException("{$file} exists and was not generated by the WordPress importer; move it away or pass --force.");
        }

        if (is_file($file) && ! $this->force) {
            $this->skipped[] = $file;

            return;
        }

        if (! is_dir(dirname($file))) {
            mkdir(dirname($file), 0755, true);
        }

        file_put_contents($file, $content);
        $this->written[] = $file;
    }

    private function mark(): string
    {
        return self::MARK.'. Regenerate rather than edit.';
    }

    private function typeTable(Type $type): string
    {
        $lines = [
            '$table->id();',
            "\$table->foreignId('site_id')->nullable()->index();",
            "\$table->unsignedBigInteger('wordpress_id')->nullable()->unique();",
            "\$table->json('name');",
            "\$table->json('code');",
            "\$table->boolean('active')->default(true);",
            "\$table->dateTime('active_from')->nullable();",
            "\$table->integer('sort')->default(500);",
        ];

        if ($type->hierarchical) {
            $lines[] = "\$table->foreignId('parent_id')->nullable()->index();";
        }

        array_push($lines,
            "\$table->string('preview_picture', 500)->nullable();",
            "\$table->json('preview_text')->nullable();",
            "\$table->json('detail_text')->nullable();",
        );

        foreach ($type->fields as $field) {
            $lines[] = match ($field->storage()) {
                'json' => "\$table->json('{$field->column}')->nullable();",
                'decimal' => "\$table->decimal('{$field->column}', 20, 6)->nullable();",
                'boolean' => "\$table->boolean('{$field->column}')->nullable();",
                'date' => "\$table->date('{$field->column}')->nullable();",
                'datetime' => "\$table->dateTime('{$field->column}')->nullable();",
                'string' => "\$table->string('{$field->column}', 500)->nullable();",
                default => "\$table->text('{$field->column}')->nullable();",
            };
        }

        $lines[] = '$table->timestamps();';

        return $this->indent($lines, 3);
    }

    private function taxonomyTable(Taxonomy $taxonomy): string
    {
        $lines = [
            '$table->id();',
            "\$table->foreignId('site_id')->nullable()->index();",
            "\$table->unsignedBigInteger('wordpress_id')->nullable()->unique();",
            "\$table->json('name');",
            "\$table->string('code');",
            "\$table->json('description')->nullable();",
        ];

        if ($taxonomy->hierarchical) {
            $lines[] = "\$table->foreignId('parent_id')->nullable()->index();";
        }

        $lines[] = "\$table->integer('sort')->default(500);";
        $lines[] = '$table->timestamps();';

        return $this->indent($lines, 3);
    }

    private function authorsTable(Plan $plan): string
    {
        return $this->indent([
            '$table->id();',
            "\$table->unsignedBigInteger('wordpress_id')->nullable()->unique();",
            "\$table->string('name');",
            "\$table->string('code');",
            "\$table->string('email')->nullable();",
            "\$table->string('url', 500)->nullable();",
            "\$table->text('description')->nullable();",
            '$table->timestamps();',
        ], 3);
    }

    private function pivotTable(string $table): string
    {
        return $this->indent([
            "\$table->unsignedBigInteger('record_id');",
            "\$table->unsignedBigInteger('related_id')->index();",
            "\$table->unique(['record_id', 'related_id']);",
        ], 3);
    }

    private function typeModel(Plan $plan, Type $type): string
    {
        $translatable = ['name', 'code', 'preview_text', 'detail_text'];
        $casts = ["'active' => 'boolean'", "'active_from' => 'datetime'", "'sort' => 'integer'"];
        $fields = [
            "Fields\\CheckboxField::make('active')->label(__('atrium::fields.standard.active'))->default(true),",
            "Fields\\DateTimeField::make('active_from')->label(__('atrium::fields.standard.active_from')),",
            "Fields\\TextField::make('name')->label(__('atrium::fields.standard.name'))->required(),",
            "Fields\\SlugField::make('code')->label(__('atrium::fields.standard.code'))->from('name'),",
            "Fields\\NumberField::make('sort')->label(__('atrium::fields.standard.sort'))->default(500),",
        ];

        if ($type->hierarchical) {
            $fields[] = "Fields\\TreeSelectField::make('parent_id')->label('Parent')->model(self::class),";
        }

        array_push($fields,
            "Fields\\ImageField::make('preview_picture')->label(__('atrium::fields.standard.preview_picture'))->directory('{$type->table}'),",
            "Fields\\ContentField::make('preview_text')->label(__('atrium::fields.standard.preview_text')),",
            "Fields\\ContentField::make('detail_text')->label(__('atrium::fields.standard.detail_text')),",
        );

        foreach ($type->fields as $field) {
            if ($field->translatable()) {
                $translatable[] = $field->column;
            }

            $cast = match ($field->storage()) {
                'json' => $field->translatable() ? null : 'array',
                'boolean' => 'boolean',
                'decimal' => 'float',
                'date' => 'date',
                'datetime' => 'datetime',
                default => null,
            };

            if ($cast !== null) {
                $casts[] = $this->q($field->column)." => '{$cast}'";
            }

            $fields[] = $this->field($field)."->tab('fields'),";
        }

        [$relations, $links] = $this->linkFields($plan, $type);

        return $this->classBody(
            $type->table,
            $type->label,
            $translatable,
            $casts,
            [...$fields, ...$links],
            [
                "TextColumn::make('id')->label(__('atrium::fields.standard.id'))->sortable(),",
                "TextColumn::make('name')->label(__('atrium::fields.standard.name'))->sortable()->searchable(),",
                "DateColumn::make('active_from')->label(__('atrium::fields.standard.active_from'))->sortable(),",
                "BooleanColumn::make('active')->label(__('atrium::fields.standard.active')),",
            ],
            $relations,
            'active_from',
            $type->fields !== [],
            "the WordPress post type \"{$type->type}\"",
        );
    }

    private function taxonomyModel(Plan $plan, Taxonomy $taxonomy): string
    {
        $fields = [
            "Fields\\TextField::make('name')->label(__('atrium::fields.standard.name'))->required(),",
            "Fields\\SlugField::make('code')->label(__('atrium::fields.standard.code'))->from('name'),",
        ];

        if ($taxonomy->hierarchical) {
            $fields[] = "Fields\\TreeSelectField::make('parent_id')->label('Parent')->model(self::class),";
        }

        $fields[] = "Fields\\NumberField::make('sort')->label(__('atrium::fields.standard.sort'))->default(500),";
        $fields[] = "Fields\\TextareaField::make('description')->label('Description'),";

        $relations = [];

        foreach ($taxonomy->types as $name) {
            $type = $plan->type($name);

            if ($type !== null && $type->moves()) {
                $relations[] = $this->inverse($type, $taxonomy->pivot($type));
                $fields[] = "Fields\\BelongsToManyField::make('{$type->table}')->label(".$this->q($type->label).")->model(\\{$type->model}::class),";
            }
        }

        return $this->classBody(
            $taxonomy->table,
            $taxonomy->label,
            ['name', 'description'],
            ["'sort' => 'integer'"],
            $fields,
            [
                "TextColumn::make('id')->label(__('atrium::fields.standard.id'))->sortable(),",
                "TextColumn::make('name')->label(__('atrium::fields.standard.name'))->sortable()->searchable(),",
                "TextColumn::make('code')->label(__('atrium::fields.standard.code'))->sortable(),",
            ],
            $relations,
            'sort',
            false,
            "the WordPress taxonomy \"{$taxonomy->taxonomy}\"",
        );
    }

    private function authorsModel(Plan $plan): string
    {
        $fields = [
            "Fields\\TextField::make('name')->label(__('atrium::fields.standard.name'))->required(),",
            "Fields\\TextField::make('code')->label(__('atrium::fields.standard.code')),",
            "Fields\\TextField::make('email')->label('E-mail'),",
            "Fields\\TextField::make('url')->label('Website'),",
            "Fields\\TextareaField::make('description')->label('Description'),",
        ];
        $relations = [];

        foreach ($plan->moving() as $type) {
            $relations[] = $this->inverse($type, $plan->authorPivot($type));
            $fields[] = "Fields\\BelongsToManyField::make('{$type->table}')->label(".$this->q($type->label).")->model(\\{$type->model}::class),";
        }

        return $this->classBody(
            $plan->authorsTable,
            'Authors',
            [],
            [],
            $fields,
            [
                "TextColumn::make('id')->label(__('atrium::fields.standard.id'))->sortable(),",
                "TextColumn::make('name')->label(__('atrium::fields.standard.name'))->sortable()->searchable(),",
                "TextColumn::make('email')->label('E-mail')->searchable(),",
            ],
            $relations,
            'name',
            null,
            'the WordPress authors',
        );
    }

    /**
     * Fields and relations of a generated record to its terms and authors.
     *
     * @return array{0:array<int,string>,1:array<int,string>}
     */
    private function linkFields(Plan $plan, Type $type): array
    {
        $relations = [];
        $fields = [];

        foreach ($type->taxonomies as $name) {
            if (($taxonomy = $plan->taxonomy($name)) === null) {
                continue;
            }

            $relations[] = $this->relation($taxonomy->table, $taxonomy->model, $taxonomy->pivot($type));
            $fields[] = "Fields\\BelongsToManyField::make('{$taxonomy->table}')->label(".$this->q($taxonomy->label).")->model(\\{$taxonomy->model}::class),";
        }

        $relations[] = $this->relation($plan->authorsTable, $plan->authorsModel, $plan->authorPivot($type));
        $fields[] = "Fields\\BelongsToManyField::make('{$plan->authorsTable}')->label('Authors')->model(\\{$plan->authorsModel}::class),";

        return [$relations, $fields];
    }

    private function relation(string $name, string $model, string $pivot): string
    {
        return <<<PHP
            /**
             * @return BelongsToMany<\\{$model},\$this>
             */
            public function {$name}(): BelongsToMany
            {
                return \$this->belongsToMany(\\{$model}::class, '{$pivot}', 'record_id', 'related_id');
            }
            PHP;
    }

    private function inverse(Type $type, string $pivot): string
    {
        return <<<PHP
            /**
             * @return BelongsToMany<\\{$type->model},\$this>
             */
            public function {$type->table}(): BelongsToMany
            {
                return \$this->belongsToMany(\\{$type->model}::class, '{$pivot}', 'related_id', 'record_id');
            }
            PHP;
    }

    /**
     * The admin field of a custom field.
     */
    private function field(Field $field): string
    {
        $label = $this->q($field->label);
        $name = $this->q($field->column);
        $options = $this->q($field->choices);

        return match (true) {
            in_array($field->kind, ['textarea', 'meta'], true) => "Fields\\TextareaField::make({$name})->label({$label})",
            $field->kind === 'wysiwyg' => "Fields\\ContentField::make({$name})->label({$label})",
            $field->kind === 'true_false' => "Fields\\CheckboxField::make({$name})->label({$label})",
            in_array($field->kind, ['number', 'range'], true) => "Fields\\NumberField::make({$name})->label({$label})",
            $field->kind === 'date_picker' => "Fields\\DateField::make({$name})->label({$label})",
            $field->kind === 'date_time_picker' => "Fields\\DateTimeField::make({$name})->label({$label})",
            $field->kind === 'image' => "Fields\\ImageField::make({$name})->label({$label})->directory('wordpress')",
            $field->kind === 'file' => "Fields\\FileField::make({$name})->label({$label})->directory('wordpress')",
            $field->kind === 'gallery' => "Fields\\GalleryField::make({$name})->label({$label})->directory('wordpress')",
            $field->kind === 'checkbox' || ($field->multiple && $field->kind === 'select') => "Fields\\MultiSelectField::make({$name})->label({$label})->options({$options})",
            in_array($field->kind, ['select', 'radio', 'button_group'], true) => "Fields\\SelectField::make({$name})->label({$label})->options({$options})",
            $field->isJson() => "Fields\\DisplayField::make({$name})->label({$label})->html(static fn (\$record): string => '<pre>'.e((string) json_encode(\$record->{$field->column}, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES)).'</pre>')",
            default => "Fields\\TextField::make({$name})->label({$label})",
        };
    }

    /**
     * @param  array<int,string>  $translatable
     * @param  array<int,string>  $casts
     * @param  array<int,string>  $fields
     * @param  array<int,string>  $columns
     * @param  array<int,string>  $relations
     * @param  bool|null  $fieldsTab  whether the form has a tab for the custom fields; null: the model belongs to no site, so it has no tabs
     */
    private function classBody(
        string $table,
        string $label,
        array $translatable,
        array $casts,
        array $fields,
        array $columns,
        array $relations,
        string $sort,
        ?bool $fieldsTab,
        string $origin,
    ): string {
        $siteBound = $fieldsTab !== null;
        $traits = $siteBound
            ? ['\\Atrium\\Admin\\Traits\\BelongsToSite', '\\Atrium\\Admin\\Traits\\HasAdminSeo', '\\Atrium\\Admin\\Traits\\HasAdminTabs', 'InteractsWithAdmin']
            : ['InteractsWithAdmin'];

        if ($translatable !== []) {
            $traits[] = '\\Atrium\\Admin\\Traits\\Translatable';
        }

        $lines = [
            "/** Records from {$origin}. */",
            'use '.implode(', ', $traits).';',
            '',
            "protected \$table = '{$table}';",
            '',
            "protected \$guarded = ['id'];",
        ];

        if ($translatable !== []) {
            array_push($lines, '', '/** @var array<int,string> */', 'protected array $translatable = '.$this->q($translatable).';');
        }

        array_push($lines,
            '',
            'protected function casts(): array',
            '{',
            '    return ['.implode(', ', $casts).'];',
            '}',
            '',
            'public static function getAdminLabel(): string',
            '{',
            '    return '.$this->q($label).';',
            '}',
            '',
            'public static function getAdminRoutePrefix(): string',
            '{',
            "    return '".str_replace('_', '-', $table)."';",
            '}',
            '',
            'public static function getDefaultSortColumn(): string',
            '{',
            "    return '{$sort}';",
            '}',
        );

        if ($siteBound) {
            $tabs = [
                "        ['name' => 'params', 'label' => __('atrium::fields.tabs.main')],",
                ...($fieldsTab ? ["        ['name' => 'fields', 'label' => __('atrium::fields.tabs.custom_fields')],"] : []),
                "        ['name' => 'seo', 'label' => __('atrium::fields.tabs.seo')],",
            ];
            $lines = [...$lines, '', 'public static function getAdminTabs(): array', '{', '    return [', ...$tabs, '    ];', '}'];
        }

        $lines = [
            ...$lines,
            '',
            'public static function getAdministrationFields(): array',
            '{',
            '    return [',
            ...array_map(static fn (string $field): string => '        '.$field, $fields),
            '    ];',
            '}',
            '',
            'public static function getAdministrationListColumns(): array',
            '{',
            '    return [',
            ...array_map(static fn (string $column): string => '        '.$column, $columns),
            '    ];',
            '}',
        ];

        foreach ($relations as $relation) {
            $lines[] = '';
            array_push($lines, ...explode("\n", $relation));
        }

        return $this->indent($lines, 1);
    }

    /**
     * @param  array<int,string>  $lines
     */
    private function indent(array $lines, int $level): string
    {
        $pad = str_repeat('    ', $level);

        return implode("\n", array_map(static fn (string $line): string => $line === '' ? '' : $pad.$line, $lines));
    }

    private function q(mixed $value): string
    {
        if (is_array($value)) {
            $items = [];

            foreach ($value as $key => $item) {
                $items[] = (array_is_list($value) ? '' : var_export((string) $key, true).' => ').var_export($item, true);
            }

            return '['.implode(', ', $items).']';
        }

        return var_export($value, true);
    }
}
